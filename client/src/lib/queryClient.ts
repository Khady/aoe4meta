import { QueryClient, QueryFunction } from "@tanstack/react-query";

// NOTE: This application is now a static website and makes direct API calls to AoE4World.
// The functions below (apiRequest, getQueryFn) are legacy code from when this used a backend proxy.
// They are kept for backwards compatibility but are NOT currently used.
// All data fetching is done with plain fetch() calls directly to https://aoe4world.com/api/v0/
// DO NOT use these functions for new features - use direct fetch() calls instead.

async function throwIfResNotOk(res: Response) {
  if (!res.ok) {
    const text = (await res.text()) || res.statusText;
    throw new Error(`${res.status}: ${text}`);
  }
}

export async function apiRequest(
  method: string,
  url: string,
  data?: unknown | undefined,
): Promise<Response> {
  const res = await fetch(url, {
    method,
    headers: data ? { "Content-Type": "application/json" } : {},
    body: data ? JSON.stringify(data) : undefined,
    credentials: "include",
  });

  await throwIfResNotOk(res);
  return res;
}

type UnauthorizedBehavior = "returnNull" | "throw";
export const getQueryFn: <T>(options: {
  on401: UnauthorizedBehavior;
}) => QueryFunction<T> =
  ({ on401: unauthorizedBehavior }) =>
  async ({ queryKey }) => {
    const res = await fetch(queryKey.join("/") as string, {
      credentials: "include",
    });

    if (unauthorizedBehavior === "returnNull" && res.status === 401) {
      return null;
    }

    await throwIfResNotOk(res);
    return await res.json();
  };

export const queryClient = new QueryClient({
  defaultOptions: {
    queries: {
      // NOTE: No default queryFn - this application uses direct fetch() calls.
      // If you need to use TanStack Query, provide your own queryFn that calls AoE4World API directly.
      refetchInterval: false,
      refetchOnWindowFocus: false,
      staleTime: Infinity,
      retry: false,
    },
    mutations: {
      retry: false,
    },
  },
});
